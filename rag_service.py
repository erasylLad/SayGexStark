def query_rag(message: str, lang: str = "ru") -> str:
    clean_message = message.lower().strip()
    if not clean_message:
        return "🤖 Пожалуйста, введите ваш вопрос."
        
    # Быстрый семантический поиск по корням слов прямо в оперативной памяти
    docs = KNOWLEDGE_BASE.get(lang, KNOWLEDGE_BASE["ru"])
    for item in docs:
        if any(keyword in clean_message for keyword in item["keywords"]):
            prefix = "Digital Buddy (ИИ-Наставник)" if lang == "ru" else "Digital Buddy (ИИ-Кеңесші)"
            source_label = "Документ-источник" if lang == "ru" else "Ресми құжат"
            return f"🤖 [b]{prefix}:[/b]\n\n{item['text']}\n\n📖 [i]{source_label}: {item['document']}[/i]"

    # Если точного совпадения не найдено
    if lang == "ru":
        return "🤖 [b]Digital Buddy:[/b]\n\nДанный вопрос выходит за рамки моих базовых регламентов. Я перенаправил этот запрос вашему HR-менеджеру, скоро он свяжется с вами!"
    else:
        return "🤖 [b]Digital Buddy:[/b]\n\nБұл сұрақ қолжетімді құжаттардың аясынан тыс. Сұраныс HR-менеджеріңізге бағытталды!"

